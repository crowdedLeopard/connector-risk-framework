/**
 * Writes powerplatform/docs/DATA-MODEL.md from schema.mjs, so the documentation can never drift
 * from the tables that provisioning creates. A test fails when the committed file is out of date.
 *
 *   node powerplatform/dataverse/document.mjs           write the file
 *   node powerplatform/dataverse/document.mjs --check   exit 1 if the file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CHOICES, PUBLISHER, SOLUTION, TABLES } from "./schema.mjs";

const TYPE_LABELS = { String: "Text", Memo: "Multiline text", Integer: "Whole number", Boolean: "Yes/no", DateOnly: "Date only", Picklist: "Choice" };

function columnType(c) {
  if (c.type === "Picklist") return `Choice (\`${c.optionSet}\`)`;
  if (c.format === "Url") return "URL";
  if (c.type === "String" || c.type === "Memo") return `${TYPE_LABELS[c.type]} (${c.max.toLocaleString("en-GB")})`;
  return TYPE_LABELS[c.type] ?? c.type;
}

/** @returns {string} the whole Markdown document */
export function render() {
  const out = [];
  const line = (s = "") => out.push(s);
  line("# Data model");
  line();
  line("<!-- Generated by powerplatform/dataverse/document.mjs from schema.mjs. Do not edit by hand. -->");
  line();
  line(`All tables belong to the solution \`${SOLUTION.uniquename}\` (version ${SOLUTION.version}), published by \`${PUBLISHER.uniquename}\` with the prefix \`${PUBLISHER.customizationprefix}\`.`);
  line("Provisioning creates everything below and is safe to run again: it adds what is missing and leaves the rest alone.");
  line();
  line("There is deliberately no risk score column. The app stores facts, traits, the organisation's criteria and its decisions, and derives each treatment at run time with the same engine as the public site.");
  line();
  line("## Relationships");
  line();
  line("```mermaid");
  line("erDiagram");
  for (const t of TABLES) for (const l of t.lookups ?? []) line(`  ${l.target} ||--o{ ${t.name} : "${l.label.toLowerCase()} (${l.cascadeDelete === "Cascade" ? "delete cascades" : "delete unlinks"})"`);
  line("```");
  line();
  line("## Tables");
  for (const t of TABLES) {
    line();
    line(`### ${t.label} (\`${t.name}\`)`);
    line();
    line(t.description);
    line();
    line(`Entity set \`${t.set}\`. ${t.ownership === "UserOwned" ? "Owned by a user or team, so the owner is accountable for the record." : "Owned by the organisation."} Auditing is on.`);
    if (t.keys?.length) line(`Alternate key${t.keys.length > 1 ? "s" : ""}: ${t.keys.map((k) => `\`${k.name}\` on ${k.columns.map((c) => `\`${c}\``).join(", ")}`).join("; ")}.`);
    line();
    line("| Column | Label | Type |");
    line("| --- | --- | --- |");
    line(`| \`${t.primary.name}\` | ${t.primary.label} | Primary name, text (${t.primary.max}) |`);
    for (const c of t.columns) line(`| \`${c.name}\` | ${c.label} | ${columnType(c)}${c.required ? ", required" : ""} |`);
    for (const l of t.lookups ?? []) line(`| \`${l.name}\` | ${l.label} | Lookup to \`${l.target}\` |`);
  }
  line();
  line("## Choices");
  line();
  line("Global choices, so every table and any report shares one set of values. Each option's key is the string the repository's data files use.");
  for (const [name, c] of Object.entries(CHOICES)) {
    line();
    line(`### ${c.label} (\`${name}\`)`);
    line();
    line("| Value | Key | Label |");
    line("| --- | --- | --- |");
    for (const [key, label] of c.options) line(`| ${c.values[key]} | \`${key}\` | ${label} |`);
  }
  line();
  return out.join("\n");
}

const target = fileURLToPath(new URL("../docs/DATA-MODEL.md", import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // A missing file is out of date too.
    }
    if (current !== text) {
      console.error("powerplatform/docs/DATA-MODEL.md is out of date. Run: node powerplatform/dataverse/document.mjs");
      process.exitCode = 1;
    }
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${target}`);
  }
}
